
# list element (How to access list element):

l1 = [50,20,80,10,60,40]  # l1 is variable [list object]
print(l1)
print(l1[0])   # [index start of 0 is 50]
print(l1[1],l1[2]) # [index of 1 is 20 and index of 2 is 80]
print(l1[-1],l1[-2])  #  Nagetive => [40 => last element start for nagetive index of 5 its call 40]

